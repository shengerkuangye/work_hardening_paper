  parameter_row("state",stateRow.sample,stateRow.variant, ...
    stateRow.support,stateRow.weighting,"peak_near_tie_audit", ...
    string(double(nearTieAudit)),"logical","audit", ...
    "One when the audit grid has a distant nearly tied peak.")
  parameter_row("state",stateRow.sample,stateRow.variant, ...
    stateRow.support,stateRow.weighting,"peak_grid_stable", ...
    string(double(isStable)),"logical","audit", ...
    "One when grid distance is within tolerance and neither grid has a distant tied peak.")
  };
end

