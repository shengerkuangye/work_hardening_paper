function render_ad_figures(adTable,textureDir)
primary = adTable.weighting=="pixel_weighted" & ...
  adTable.bin_width_deg==2 & ...
  ismember(adTable.support,["raw_full","denoised_full"]);
pdfMaximum = max(adTable.pdf_per_degree(primary));
mrdMaximum = max(adTable.mrd(primary));
assert(isfinite(pdfMaximum) && pdfMaximum > 0);
assert(isfinite(mrdMaximum) && mrdMaximum > 0);
yLimits = struct("pdf",[0 1.05*pdfMaximum], ...
  "mrd",[0 max(1.05,1.05*mrdMaximum)]);
render_one_ad_figure(adTable(primary & ...
  adTable.support=="raw_full",:),"raw", ...
  fullfile(textureDir,"c_axis_ad_distribution_raw.png"),yLimits);
render_one_ad_figure(adTable(primary & ...
  adTable.support=="denoised_full",:),"denoised", ...
  fullfile(textureDir,"c_axis_ad_distribution_denoised.png"),yLimits);
end

function render_one_ad_figure(rows,variantName,outputPath,yLimits)
samples = unique(rows(:,["sample","cold_reduction_percent"]),"rows");
[~,order] = sort(samples.cold_reduction_percent);
samples = samples(order,:);
assert(height(samples) == 6);
colors = lines(6);
lineStyles = ["-","--",":","-.","-","--"];
figureHandle = figure("Visible","off","Color","white", ...
  "Position",[80 80 1300 1050]);
cleanupFigure = onCleanup(@() close(figureHandle));
layout = tiledlayout(figureHandle,2,1,"Padding","compact", ...
  "TileSpacing","compact");
pdfAxes = nexttile(layout);
mrdAxes = nexttile(layout);
hold(pdfAxes,"on");
hold(mrdAxes,"on");
for sampleIndex = 1:height(samples)
  selected = rows.sample==samples.sample(sampleIndex);
  sampleRows = sortrows(rows(selected,:),"bin_center_deg");
  label = sprintf("%s (%.2f%%)",samples.sample(sampleIndex), ...
    samples.cold_reduction_percent(sampleIndex));
  plot(pdfAxes,sampleRows.bin_center_deg,sampleRows.pdf_per_degree, ...
    "Color",colors(sampleIndex,:),"LineStyle", ...
    lineStyles(sampleIndex),"LineWidth",1.6,"DisplayName",label);
  plot(mrdAxes,sampleRows.bin_center_deg,sampleRows.mrd, ...
    "Color",colors(sampleIndex,:),"LineStyle", ...
    lineStyles(sampleIndex),"LineWidth",1.6,"DisplayName",label);
end
yline(mrdAxes,1,"-","Random axes (MRD = 1)", ...
  "Color",[0.35 0.35 0.35],"LineWidth",1.0, ...
  "HandleVisibility","off");
xlim(pdfAxes,[0 90]);
xlim(mrdAxes,[0 90]);
ylim(pdfAxes,yLimits.pdf);
ylim(mrdAxes,yLimits.mrd);
ylabel(pdfAxes,"Probability density (degree^{-1})");
ylabel(mrdAxes,"MRD");
xlabel(mrdAxes,"Acute c-axis angle to AD (deg)");
grid(pdfAxes,"on");
grid(mrdAxes,"on");
legend(pdfAxes,"Location","eastoutside","Interpreter","none");
title(layout,sprintf( ...
  "c-axis distribution relative to AD | %s | pixel_weighted | %s_full | bin = 2 deg", ...
  variantName,variantName),"Interpreter","none");
exportgraphics(figureHandle,char(outputPath),"Resolution",300, ...
  "BackgroundColor","white");
clear cleanupFigure
end

function render_spherical_figures(sphericalTable,densityModels, ...
  textureDir,parameterTable)
colorRows = parameterTable.parameter=="color_maximum_mrd";
colorMaximums = double(parameterTable.value(colorRows));
assert(~isempty(colorMaximums) && ...
  max(abs(colorMaximums-colorMaximums(1))) < 1e-12);
colorMaximum = colorMaximums(1);
render_one_spherical_figure(densityModels,"raw",colorMaximum, ...
  fullfile(textureDir,"c_axis_spherical_distribution_raw.png"));
render_one_spherical_figure(densityModels,"denoised",colorMaximum, ...
  fullfile(textureDir,"c_axis_spherical_distribution_denoised.png"));
pooled = sphericalTable.weighting=="pixel_weighted" & ...
  sphericalTable.kernel_halfwidth_deg==5 & ...
  ismember(sphericalTable.support,["raw_full","denoised_full"]);
assert(mean(sphericalTable.mrd(pooled) > colorMaximum) <= 0.002);
end

function render_one_spherical_figure(models,variantName, ...
  colorMaximum,outputPath)
selected = string({models.variant})'==variantName;
models = models(selected);
reductions = zeros(numel(models),1);
for modelIndex = 1:numel(models)
  reductions(modelIndex) = models(modelIndex).cold_reduction_percent;
end
[~,order] = sort(reductions);
models = models(order);
reductions = reductions(order);
assert(numel(models) == 6);

figureHandle = figure("Visible","off","Color","white", ...
  "Position",[40 40 1800 1150]);
cleanupFigure = onCleanup(@() close(figureHandle));
layout = tiledlayout(figureHandle,2,3,"Padding","compact", ...
  "TileSpacing","compact");
contourLevels = linspace(0,colorMaximum,11);
lastAxes = [];
for modelIndex = 1:numel(models)
  axesHandle = nexttile(layout);
  lastAxes = axesHandle;
  plot(models(modelIndex).density_function, ...
    'antipodal','earea','contourf','silent', ...
    'parent',axesHandle,'colorRange',[0 colorMaximum], ...
    'contours',contourLevels);
  title(axesHandle,sprintf("%s | %.2f%%", ...
    models(modelIndex).sample,reductions(modelIndex)), ...
    "Interpreter","none","FontWeight","normal");
  annotate_specimen_axes(axesHandle);
  if models(modelIndex).peak_grid_stable
    peak = peak_xyz(models(modelIndex).maximum_theta_ad_deg, ...
      models(modelIndex).maximum_phi_about_ad_deg);
    hold(axesHandle,"on");
    plot(vector3d(peak(1),peak(2),peak(3)), ...
      'Marker','o','MarkerSize',4,'MarkerFaceColor', ...
      [0.25 0.25 0.25],'MarkerEdgeColor',[1 1 1], ...
      'LineStyle','none','parent',axesHandle,'silent');
  end
end
colorbarHandle = colorbar(lastAxes,"eastoutside");
colorbarHandle.Label.String = "MRD";
title(layout,sprintf( ...
  "Antipodal c-axis spherical distribution | %s | pixel_weighted | %s_full | kernel = 5 deg | phi+: TD/RD to ND about +AD", ...
  variantName,variantName), ...
  "Interpreter","none");
exportgraphics(figureHandle,char(outputPath),"Resolution",300, ...
  "BackgroundColor","white");
clear cleanupFigure
end

function annotate_specimen_axes(axesHandle)
common = {'Units','normalized','BackgroundColor','white', ...
  'Margin',1,'FontSize',8,'Interpreter','none'};
text(axesHandle,0.97,0.50,'AD',common{:}, ...
  'HorizontalAlignment','right','VerticalAlignment','middle');
text(axesHandle,0.50,0.97,'TD/RD',common{:}, ...
  'HorizontalAlignment','center','VerticalAlignment','top');
text(axesHandle,0.50,0.50,'ND',common{:}, ...
  'HorizontalAlignment','center','VerticalAlignment','middle');
end
