  "purpose"; "load_geometry"; "load_axis"; "grain_orientation"; ...
  "family_grain_value"; "included_families"; ...
  "schmid_thresholds"; "crss_competition_ratio"; ...
  "ratio_thresholds"; "prismatic_a_crss_mpa"; ...
  "basal_a_crss_mpa"; "pyramidal_ca_crss_mpa"; "crss_source"; ...
  "grain_detection_threshold_deg"; "minimum_grain_pixels"; ...
  "primary_input"; "sensitivity_input"; "interpretive_limit"];
value = [ ...
  "compare fixed Schmid-factor statistical definitions without post-hoc deletion"; ...
  "uniaxial tension"; "AD (vector3d.X)"; ...
  "mean orientation of each retained reconstructed Ti-Hex grain"; ...
  "maximum absolute value across all symmetrised variants"; ...
  "prismatic_a, basal_a, pyramidal_ca"; ...
  join(string(compose("%.2f", sfThresholds)), ","); ...
  "R_ca = (m_ca/756)/max(m_prismatic/154,m_basal/252)"; ...
  join(string(compose("%.2f", ratioThresholds)), ","); ...
  string(crssMPa(1)); string(crssMPa(2)); string(crssMPa(3)); ...
  "Xiong et al., Acta Materialia 199 (2020) 561-577, Table 4"; ...
  string(reconstructionOptions.detection_threshold_deg); ...
  string(reconstructionOptions.min_grain_pixels); ...
  "raw CTF"; "denoised CTF"; ...
  "geometric and fixed-CRSS screening only; thresholds are all reported as a sensitivity grid; no row is discarded from the denominator; local stress, hardening and observed Burgers vectors are unresolved"];
writetable(table(parameter, value), fullfile(outputRoot, ...
  "schmid_statistical_sensitivity_parameters.csv"));
end

function plot_sensitivity(summary, thresholdSensitivity, ratioSummary, ...
  outputRoot, families, displayNames)
colors = [0.10 0.43 0.72; 0.86 0.33 0.10; 0.45 0.24 0.65];
markers = {'o', 's', '^'};
xValues = unique(summary.cold_reduction_percent);

figureHandle = figure("Visible", "off", "Color", "white", ...
  "Units", "inches", "Position", [0.5 0.5 12.0 8.1], ...
  "PaperPositionMode", "auto");
cleanupFigure = onCleanup(@() close(figureHandle));
layout = tiledlayout(figureHandle, 2, 2, ...
  "Padding", "compact", "TileSpacing", "compact");

axesMean = nexttile(layout);
hold(axesMean, "on");
for familyIndex = 1:numel(families)
  plot_family_variants(axesMean, summary, families(familyIndex), ...
    "area_weighted_mean_schmid", colors(familyIndex, :), ...
    markers{familyIndex}, displayNames(familyIndex));
end
format_axes(axesMean, xValues);
ylabel(axesMean, "Area-weighted mean |m|max");
title(axesMean, "(a) Mean of grain-family maxima", ...
  "FontWeight", "normal");
legend(axesMean, "Location", "southoutside", "NumColumns", 3, ...
  "Box", "off", "FontSize", 8.0);

axesQuantile = nexttile(layout);
hold(axesQuantile, "on");
for familyIndex = [1, 3]
  plot_family_variants(axesQuantile, summary, families(familyIndex), ...
    "area_weighted_q90_schmid", colors(familyIndex, :), ...
    markers{familyIndex}, displayNames(familyIndex));
end
format_axes(axesQuantile, xValues);
ylabel(axesQuantile, "Area-weighted 90th percentile |m|max");
title(axesQuantile, "(b) Upper-distribution location", ...
  "FontWeight", "normal");
legend(axesQuantile, "Location", "southoutside", "NumColumns", 2, ...
  "Box", "off", "FontSize", 8.0);

axesTail = nexttile(layout);
hold(axesTail, "on");
for familyIndex = [1, 3]
  rows = thresholdSensitivity.family == families(familyIndex) & ...
    abs(thresholdSensitivity.schmid_threshold - 0.46) < 1e-12;
  selected = thresholdSensitivity(rows, :);
  plot_family_variants(axesTail, selected, families(familyIndex), ...
    "selected_grain_area_percent", colors(familyIndex, :), ...
    markers{familyIndex}, displayNames(familyIndex));
end
format_axes(axesTail, xValues);
ylabel(axesTail, "Grain area with |m|max >= 0.46 (%)");
title(axesTail, "(c) Fixed high-tail threshold", ...
  "FontWeight", "normal");
legend(axesTail, "Location", "southoutside", "NumColumns", 2, ...
  "Box", "off", "FontSize", 8.0);

axesRatio = nexttile(layout);
hold(axesRatio, "on");
ratioRows = ratioSummary.ratio_name == "ca_to_best_a";
selected = ratioSummary(ratioRows, :);
plot_variant_metric(axesRatio, selected, ...
  "area_weighted_median_ratio", colors(3, :), 'o', ...
  "Median Rca/best-a");
plot_variant_metric(axesRatio, selected, ...
  "area_weighted_q90_ratio", colors(1, :), '^', ...
  "90th percentile Rca/best-a");
yline(axesRatio, 1, ":", "Color", [0.25 0.25 0.25], ...
  "LineWidth", 1.0, "HandleVisibility", "off");
format_axes(axesRatio, xValues);
ylabel(axesRatio, "CRSS-normalized competition ratio");
title(axesRatio, "(d) Pyramidal <c+a> relative to best <a>", ...
  "FontWeight", "normal");
legend(axesRatio, "Location", "southoutside", "NumColumns", 2, ...
  "Box", "off", "FontSize", 8.0);

xlabel(layout, "Cold reduction (%)");
title(layout, "Schmid-factor statistical sensitivity under AD tension", ...
  "FontName", "Arial", "FontSize", 13, "FontWeight", "bold");
subtitle(layout, ...
  "Solid: raw EBSD; dashed: denoised sensitivity; no threshold-selected rows are deleted", ...
  "FontName", "Arial", "FontSize", 9.2);
drawnow;

figureStem = fullfile(outputRoot, ...
  "schmid_statistical_sensitivity_6state");
exportgraphics(figureHandle, figureStem + ".png", ...
  "Resolution", 600, "BackgroundColor", "white");
exportgraphics(figureHandle, figureStem + ".tif", ...
  "Resolution", 600, "BackgroundColor", "white");
clear cleanupFigure
end

function plot_family_variants(axesHandle, input, family, metric, ...
  color, marker, label)
rows = input.family == family;
selected = input(rows, :);
plot_variant_metric(axesHandle, selected, metric, color, marker, label);
end

function plot_variant_metric(axesHandle, input, metric, color, marker, label)
raw = sortrows(input(input.variant == "raw", :), ...
  "cold_reduction_percent");
denoised = sortrows(input(input.variant == "denoised", :), ...
  "cold_reduction_percent");
assert(height(raw) == 6 && height(denoised) == 6);
plot(axesHandle, raw.cold_reduction_percent, raw.(char(metric)), ...
  ['-' marker], "Color", color, "LineWidth", 1.55, ...
  "MarkerSize", 5.8, "MarkerFaceColor", color, ...
  "DisplayName", label);
plot(axesHandle, denoised.cold_reduction_percent, ...
  denoised.(char(metric)), ...
  ['--' marker], "Color", color, "LineWidth", 1.0, ...
  "MarkerSize", 5.0, "MarkerFaceColor", "white", ...
  "HandleVisibility", "off");
end

function plot_initial_final_ccdf(thresholdSensitivity, outputRoot, ...
  families, displayNames)
colors = [0.10 0.43 0.72; 0.45 0.24 0.65];
targetIndices = [1, 3];
figureHandle = figure("Visible", "off", "Color", "white", ...
  "Units", "inches", "Position", [0.5 0.5 10.8 4.6], ...
  "PaperPositionMode", "auto");
cleanupFigure = onCleanup(@() close(figureHandle));
layout = tiledlayout(figureHandle, 1, 2, ...
  "Padding", "compact", "TileSpacing", "compact");
for panelIndex = 1:2
  familyIndex = targetIndices(panelIndex);
  axesHandle = nexttile(layout);
  hold(axesHandle, "on");
  for variantIndex = 1:2
    variant = ["raw", "denoised"];
    lineStyle = ["-", "--"];
    for stateIndex = 1:2
      sample = ["7d", "5d"];
      marker = {'o', '^'};
      rows = thresholdSensitivity.family == families(familyIndex) & ...
        thresholdSensitivity.variant == variant(variantIndex) & ...
        thresholdSensitivity.sample == sample(stateIndex);
      selected = sortrows(thresholdSensitivity(rows, :), ...
        "schmid_threshold");
      assert(height(selected) == 8);
      visibility = "on";
      if variantIndex == 2
        visibility = "off";
      end
      lineSpec = char(lineStyle(variantIndex) + ...
        string(marker{stateIndex}));
      plot(axesHandle, selected.schmid_threshold, ...
        selected.selected_grain_area_percent, ...
        lineSpec, ...
        "Color", colors(stateIndex, :), "LineWidth", 1.4, ...
        "MarkerSize", 5.0, "MarkerFaceColor", ...
        colors(stateIndex, :), "HandleVisibility", visibility, ...
        "DisplayName", sample(stateIndex));
    end
  end
  xlim(axesHandle, [0.30 0.48]);
  xticks(axesHandle, 0.30:0.02:0.48);
  grid(axesHandle, "on");
  axesHandle.GridAlpha = 0.13;
  axesHandle.FontName = "Arial";
  axesHandle.FontSize = 9;
  xlabel(axesHandle, "Schmid threshold, mc");
  ylabel(axesHandle, "Grain area with |m|max >= mc (%)");
  title(axesHandle, displayNames(familyIndex), ...
    "FontWeight", "normal");
  legend(axesHandle, "Location", "southwest", "Box", "off");
end
