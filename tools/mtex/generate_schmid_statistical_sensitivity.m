function outputs = generate_schmid_statistical_sensitivity( ...
  scanRoot, outputRoot)
%GENERATE_SCHMID_STATISTICAL_SENSITIVITY Compare Schmid statistics.
%
% This analysis deliberately reports several fixed statistical views rather
% than selecting a threshold after inspecting the result. Per retained
% reconstructed grain, each family value is the maximum absolute Schmid
% factor across all symmetrised variants under AD uniaxial tension.

arguments
  scanRoot (1,1) string
  outputRoot (1,1) string
end

assert(isfolder(scanRoot), "EBSD scan folder not found: %s", scanRoot);
assert(~isempty(which("EBSD")), ...
  "MTEX is not loaded in the current MATLAB session.");
if ~isfolder(outputRoot)
  mkdir(outputRoot);
end

contract = comprehensive_ebsd_output_contract();
catalog = comprehensive_ebsd_catalog(scanRoot);
reconstructionOptions = struct( ...
  "detection_threshold_deg", ...
  contract.parameters.primary_grain_detection_deg, ...
  "min_grain_pixels", contract.parameters.min_grain_pixels);

families = ["prismatic_a"; "basal_a"; "pyramidal_ca"];
displayNames = ["Prismatic <a>"; "Basal <a>"; ...
  "Pyramidal <c+a>"];
crssMPa = [154; 252; 756];
sfThresholds = [0.30; 0.34; 0.38; 0.40; 0.42; 0.44; 0.46; 0.48];
ratioThresholds = [0.15; 0.20; 0.25; 0.30; 0.40; 0.50; 0.75; 1.00];

summary = table();
thresholdSensitivity = table();
ratioSummary = table();
ratioSensitivity = table();
preferredFamily = table();

for scanIndex = 1:height(catalog)
  catalogRow = catalog(scanIndex, :);
  fprintf("SCHMID_SENSITIVITY sample=%s variant=%s\n", ...
    catalogRow.sample, catalogRow.variant);
  [ebsdFull, ~] = load_comprehensive_ebsd_scan(catalogRow);
  [grains, ~, ~] = reconstruct_comprehensive_grains( ...
    ebsdFull, reconstructionOptions);
  retained = grains("Ti-Hex");
  retained = retained(retained.numPixel >= ...
    reconstructionOptions.min_grain_pixels);
  assert(~isempty(retained), ...
    "No retained Ti-Hex grains for %s %s.", ...
    catalogRow.sample, catalogRow.variant);

  byGrain = compute_axial_propensity_metrics( ...
    retained.meanOrientation, double(retained.id(:)), ...
    double(area(retained)));
  [schmid, grainIds, areaWeights] = align_family_values( ...
    byGrain, families);
  nGrains = numel(grainIds);

  for familyIndex = 1:numel(families)
    values = schmid(:, familyIndex);
    activationStress = crssMPa(familyIndex) ./ values;
    q05 = weighted_quantile(values, areaWeights, 0.05);
    q95 = weighted_quantile(values, areaWeights, 0.95);
    trimmed = values >= q05 & values <= q95;
    trimmedWeights = areaWeights(trimmed);
    trimmedWeights = trimmedWeights / sum(trimmedWeights);

    scanRow = table( ...
      catalogRow.sample, catalogRow.diameter_mm, ...
      catalogRow.cold_reduction_percent, catalogRow.variant, ...
      families(familyIndex), displayNames(familyIndex), ...
      crssMPa(familyIndex), nGrains, mean(values), ...
      sum(areaWeights .* values), median(values), ...
      weighted_quantile(values, areaWeights, 0.10), ...
      weighted_quantile(values, areaWeights, 0.25), ...
      weighted_quantile(values, areaWeights, 0.50), ...
      weighted_quantile(values, areaWeights, 0.75), ...
      weighted_quantile(values, areaWeights, 0.90), q95, ...
      sum(trimmedWeights .* values(trimmed)), ...
      100 * mean(values >= 0.40), ...
      100 * sum(areaWeights(values >= 0.40)), ...
      sum(areaWeights .* values) / crssMPa(familyIndex), ...
      weighted_quantile(activationStress, areaWeights, 0.25), ...
      weighted_quantile(activationStress, areaWeights, 0.50), ...
      weighted_quantile(activationStress, areaWeights, 0.75), ...
      'VariableNames', {'sample', 'diameter_mm', ...
      'cold_reduction_percent', 'variant', 'family', 'display_name', ...
      'source_crss_mpa', 'grain_count', 'count_weighted_mean_schmid', ...
      'area_weighted_mean_schmid', 'count_weighted_median_schmid', ...
      'area_weighted_q10_schmid', 'area_weighted_q25_schmid', ...
      'area_weighted_median_schmid', 'area_weighted_q75_schmid', ...
      'area_weighted_q90_schmid', 'area_weighted_q95_schmid', ...
      'area_weighted_trimmed_mean_q05_q95_schmid', ...
      'count_fraction_schmid_ge_0_40_percent', ...
      'area_fraction_schmid_ge_0_40_percent', ...
      'area_weighted_mean_drive_per_mpa', ...
      'area_weighted_q25_activation_stress_mpa', ...
      'area_weighted_median_activation_stress_mpa', ...
      'area_weighted_q75_activation_stress_mpa'});
    summary = append_table(summary, scanRow);

    for thresholdIndex = 1:numel(sfThresholds)
      threshold = sfThresholds(thresholdIndex);
      selected = values >= threshold;
      selectedCount = nnz(selected);
      if selectedCount == 0
        conditionalCountMean = NaN;
        conditionalAreaMean = NaN;
      else
        conditionalCountMean = mean(values(selected));
        conditionalWeights = areaWeights(selected);
        conditionalWeights = conditionalWeights / sum(conditionalWeights);
        conditionalAreaMean = sum(conditionalWeights .* values(selected));
      end
      thresholdRow = table( ...
        catalogRow.sample, catalogRow.diameter_mm, ...
        catalogRow.cold_reduction_percent, catalogRow.variant, ...
        families(familyIndex), displayNames(familyIndex), threshold, ...
        nGrains, selectedCount, 100 * mean(selected), ...
        100 * sum(areaWeights(selected)), conditionalCountMean, ...
        conditionalAreaMean, ...
        'VariableNames', {'sample', 'diameter_mm', ...
        'cold_reduction_percent', 'variant', 'family', 'display_name', ...
        'schmid_threshold', 'grain_count', 'selected_grain_count', ...
        'selected_grain_count_percent', 'selected_grain_area_percent', ...
        'conditional_count_mean_schmid', ...
        'conditional_area_mean_schmid'});
      thresholdSensitivity = append_table( ...
        thresholdSensitivity, thresholdRow);
    end
  end

  drive = schmid ./ crssMPa';
  bestADrive = max(drive(:, 1:2), [], 2);
  ratios = [drive(:, 3) ./ bestADrive, ...
    drive(:, 2) ./ drive(:, 1)];
  ratioNames = ["ca_to_best_a"; "basal_to_prismatic"];
  for ratioIndex = 1:numel(ratioNames)
    values = ratios(:, ratioIndex);
    ratioRow = table( ...
      catalogRow.sample, catalogRow.diameter_mm, ...
      catalogRow.cold_reduction_percent, catalogRow.variant, ...
      ratioNames(ratioIndex), nGrains, mean(values), ...
      sum(areaWeights .* values), ...
      weighted_quantile(values, areaWeights, 0.10), ...
      weighted_quantile(values, areaWeights, 0.25), ...
      weighted_quantile(values, areaWeights, 0.50), ...
      weighted_quantile(values, areaWeights, 0.75), ...
      weighted_quantile(values, areaWeights, 0.90), ...
      weighted_quantile(values, areaWeights, 0.95), max(values), ...
      'VariableNames', {'sample', 'diameter_mm', ...
      'cold_reduction_percent', 'variant', 'ratio_name', ...
      'grain_count', 'count_weighted_mean_ratio', ...
      'area_weighted_mean_ratio', 'area_weighted_q10_ratio', ...
      'area_weighted_q25_ratio', 'area_weighted_median_ratio', ...
      'area_weighted_q75_ratio', 'area_weighted_q90_ratio', ...
      'area_weighted_q95_ratio', 'maximum_ratio'});
    ratioSummary = append_table(ratioSummary, ratioRow);

    for thresholdIndex = 1:numel(ratioThresholds)
      threshold = ratioThresholds(thresholdIndex);
      selected = values >= threshold;
      ratioThresholdRow = table( ...
        catalogRow.sample, catalogRow.diameter_mm, ...
        catalogRow.cold_reduction_percent, catalogRow.variant, ...
        ratioNames(ratioIndex), threshold, nGrains, nnz(selected), ...
        100 * mean(selected), 100 * sum(areaWeights(selected)), ...
        'VariableNames', {'sample', 'diameter_mm', ...
        'cold_reduction_percent', 'variant', 'ratio_name', ...
        'ratio_threshold', 'grain_count', 'selected_grain_count', ...
        'selected_grain_count_percent', 'selected_grain_area_percent'});
      ratioSensitivity = append_table( ...
        ratioSensitivity, ratioThresholdRow);
    end
  end

  [~, preferredIndex] = max(drive, [], 2);
  for familyIndex = 1:numel(families)
    selected = preferredIndex == familyIndex;
    familyRow = table( ...
      catalogRow.sample, catalogRow.diameter_mm, ...
      catalogRow.cold_reduction_percent, catalogRow.variant, ...
      families(familyIndex), displayNames(familyIndex), ...
      nGrains, nnz(selected), 100 * mean(selected), ...
      100 * sum(areaWeights(selected)), ...
      'VariableNames', {'sample', 'diameter_mm', ...
      'cold_reduction_percent', 'variant', 'preferred_family', ...
      'display_name', 'grain_count', 'preferred_grain_count', ...
      'preferred_grain_count_percent', 'preferred_grain_area_percent'});
    preferredFamily = append_table(preferredFamily, familyRow);
  end

  clear ebsdFull grains retained byGrain schmid grainIds areaWeights
end

summary = sortrows(summary, ...
  {'cold_reduction_percent', 'variant', 'source_crss_mpa'});
thresholdSensitivity = sortrows(thresholdSensitivity, ...
  {'cold_reduction_percent', 'variant', 'family', 'schmid_threshold'});
ratioSummary = sortrows(ratioSummary, ...
  {'cold_reduction_percent', 'variant', 'ratio_name'});
ratioSensitivity = sortrows(ratioSensitivity, ...
  {'cold_reduction_percent', 'variant', 'ratio_name', 'ratio_threshold'});
preferredFamily = sortrows(preferredFamily, ...
  {'cold_reduction_percent', 'variant', 'preferred_family'});

initialFinal = build_initial_final_comparison( ...
  summary, thresholdSensitivity, ratioSummary, ratioSensitivity, families);

writetable(summary, fullfile(outputRoot, ...
  "schmid_statistical_summary.csv"));
writetable(thresholdSensitivity, fullfile(outputRoot, ...
  "schmid_threshold_sensitivity.csv"));
writetable(ratioSummary, fullfile(outputRoot, ...
  "crss_competition_ratio_summary.csv"));
writetable(ratioSensitivity, fullfile(outputRoot, ...
  "crss_competition_threshold_sensitivity.csv"));
writetable(preferredFamily, fullfile(outputRoot, ...
  "crss_preferred_family_summary.csv"));
writetable(initialFinal, fullfile(outputRoot, ...
  "initial_final_method_comparison.csv"));
write_parameters(outputRoot, reconstructionOptions, sfThresholds, ...
  ratioThresholds, crssMPa);
plot_sensitivity(summary, thresholdSensitivity, ratioSummary, ...
  outputRoot, families, displayNames);
plot_initial_final_ccdf(thresholdSensitivity, outputRoot, families, ...
  displayNames);

outputs = struct();
outputs.summary = summary;
outputs.threshold_sensitivity = thresholdSensitivity;
outputs.ratio_summary = ratioSummary;
outputs.ratio_sensitivity = ratioSensitivity;
outputs.preferred_family = preferredFamily;
outputs.initial_final = initialFinal;
end

function [schmid, grainIds, areaWeights] = ...
  align_family_values(byGrain, families)
familyTables = cell(numel(families), 1);
for familyIndex = 1:numel(families)
  rows = byGrain.family == families(familyIndex);
  familyTables{familyIndex} = sortrows( ...
    byGrain(rows, {'grain_id', 'max_abs_schmid', ...
    'area_weight'}), 'grain_id');
end
grainIds = familyTables{1}.grain_id;
areaWeights = familyTables{1}.area_weight;
areaWeights = areaWeights / sum(areaWeights);
schmid = zeros(numel(grainIds), numel(families));
for familyIndex = 1:numel(families)
  current = familyTables{familyIndex};
  assert(isequal(current.grain_id, grainIds), ...
    "Grain IDs do not align across slip families.");
  assert(max(abs(current.area_weight - familyTables{1}.area_weight)) ...
    < 1e-12, "Grain area weights do not align across slip families.");
  schmid(:, familyIndex) = current.max_abs_schmid;
end
assert(all(isfinite(schmid) & schmid > 0 & schmid <= 0.5 + 1e-10, ...
  "all"));
end

function comparison = build_initial_final_comparison( ...
  summary, thresholdSensitivity, ratioSummary, ratioSensitivity, families)
comparison = table();
summaryMethods = [ ...
  "count_weighted_mean_schmid"; ...
  "area_weighted_mean_schmid"; ...
  "count_weighted_median_schmid"; ...
  "area_weighted_median_schmid"; ...
  "area_weighted_q90_schmid"; ...
  "area_weighted_q95_schmid"; ...
  "area_weighted_trimmed_mean_q05_q95_schmid"];
for variant = ["raw", "denoised"]
  for familyIndex = 1:numel(families)
    initialRow = summary(summary.sample == "7d" & ...
      summary.variant == variant & summary.family == families(familyIndex), :);
    finalRow = summary(summary.sample == "5d" & ...
      summary.variant == variant & summary.family == families(familyIndex), :);
    assert(height(initialRow) == 1 && height(finalRow) == 1);
    for methodIndex = 1:numel(summaryMethods)
      method = summaryMethods(methodIndex);
      comparison = append_comparison(comparison, variant, ...
        "schmid_location", families(familyIndex), method, NaN, ...
        initialRow.(char(method)), finalRow.(char(method)), ...
        "schmid_factor");
    end
    for threshold = [0.40, 0.44, 0.46, 0.48]
      initialThreshold = thresholdSensitivity( ...
        thresholdSensitivity.sample == "7d" & ...
        thresholdSensitivity.variant == variant & ...
        thresholdSensitivity.family == families(familyIndex) & ...
        abs(thresholdSensitivity.schmid_threshold - threshold) < 1e-12, :);
      finalThreshold = thresholdSensitivity( ...
        thresholdSensitivity.sample == "5d" & ...
        thresholdSensitivity.variant == variant & ...
        thresholdSensitivity.family == families(familyIndex) & ...
        abs(thresholdSensitivity.schmid_threshold - threshold) < 1e-12, :);
      assert(height(initialThreshold) == 1 && height(finalThreshold) == 1);
      comparison = append_comparison(comparison, variant, ...
        "schmid_tail", families(familyIndex), ...
        "area_fraction_schmid_ge_threshold", threshold, ...
        initialThreshold.selected_grain_area_percent, ...
        finalThreshold.selected_grain_area_percent, "percentage_points");
      comparison = append_comparison(comparison, variant, ...
        "schmid_tail", families(familyIndex), ...
        "conditional_area_mean_schmid", threshold, ...
        initialThreshold.conditional_area_mean_schmid, ...
        finalThreshold.conditional_area_mean_schmid, "schmid_factor");
    end
  end

  for ratioName = ["ca_to_best_a", "basal_to_prismatic"]
    initialRatio = ratioSummary(ratioSummary.sample == "7d" & ...
      ratioSummary.variant == variant & ...
      ratioSummary.ratio_name == ratioName, :);
    finalRatio = ratioSummary(ratioSummary.sample == "5d" & ...
      ratioSummary.variant == variant & ...
      ratioSummary.ratio_name == ratioName, :);
    assert(height(initialRatio) == 1 && height(finalRatio) == 1);
    for method = ["area_weighted_mean_ratio", ...
        "area_weighted_median_ratio", "area_weighted_q90_ratio", ...
        "area_weighted_q95_ratio"]
      comparison = append_comparison(comparison, variant, ...
        "crss_competition", ratioName, method, NaN, ...
        initialRatio.(char(method)), finalRatio.(char(method)), "ratio");
    end
    for threshold = [0.20, 0.25, 0.30, 0.50, 1.00]
      initialThreshold = ratioSensitivity( ...
        ratioSensitivity.sample == "7d" & ...
        ratioSensitivity.variant == variant & ...
        ratioSensitivity.ratio_name == ratioName & ...
        abs(ratioSensitivity.ratio_threshold - threshold) < 1e-12, :);
      finalThreshold = ratioSensitivity( ...
        ratioSensitivity.sample == "5d" & ...
        ratioSensitivity.variant == variant & ...
        ratioSensitivity.ratio_name == ratioName & ...
        abs(ratioSensitivity.ratio_threshold - threshold) < 1e-12, :);
      assert(height(initialThreshold) == 1 && height(finalThreshold) == 1);
      comparison = append_comparison(comparison, variant, ...
        "crss_competition_tail", ratioName, ...
        "area_fraction_ratio_ge_threshold", threshold, ...
        initialThreshold.selected_grain_area_percent, ...
        finalThreshold.selected_grain_area_percent, "percentage_points");
    end
  end
end
end

function output = append_comparison(input, variant, metricGroup, target, ...
  method, threshold, initialValue, finalValue, unit)
absoluteChange = finalValue - initialValue;
if isfinite(initialValue) && abs(initialValue) > eps
  relativeChangePercent = 100 * absoluteChange / initialValue;
else
  relativeChangePercent = NaN;
end
row = table(variant, metricGroup, target, method, threshold, ...
  initialValue, finalValue, absoluteChange, relativeChangePercent, unit, ...
  'VariableNames', {'variant', 'metric_group', 'target', 'method', ...
  'threshold', 'initial_7d', 'final_5d', 'absolute_change', ...
  'relative_change_percent', 'unit'});
output = append_table(input, row);
end

function output = append_table(input, row)
if isempty(input)
  output = row;
else
  output = [input; row];
end
end

function result = weighted_quantile(values, weights, probability)
assert(isscalar(probability) && probability >= 0 && probability <= 1);
[sortedValues, order] = sort(values);
sortedWeights = weights(order) / sum(weights);
result = sortedValues(find(cumsum(sortedWeights) >= probability, ...
  1, "first"));
end

